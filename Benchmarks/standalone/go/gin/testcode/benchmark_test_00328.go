package testcode

import (
	"fmt"
	"net/http"

	"github.com/gin-gonic/gin"
)

func BenchmarkTest00328(c *gin.Context) {
	forwardedIP := c.GetHeader("X-Forwarded-For")
	data := fmt.Sprintf("%s", forwardedIP)
	http.SetCookie(c.Writer, &http.Cookie{Name: "session", Value: data, HttpOnly: true, SameSite: http.SameSiteStrictMode})
	c.JSON(200, gin.H{"code": "OK"})
}
