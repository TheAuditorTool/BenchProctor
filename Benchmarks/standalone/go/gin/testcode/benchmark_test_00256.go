package testcode

import (
	"net/http"

	"github.com/gin-gonic/gin"
)

func BenchmarkTest00256(c *gin.Context) {
	authHeader := c.GetHeader("Authorization")
	var data string
	if len(authHeader) > 0 {
		data = authHeader
	} else {
		data = "default"
	}
	c.Redirect(http.StatusFound, data)
}
