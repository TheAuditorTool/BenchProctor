package testcode

import (
	"net/http"

	"github.com/gin-gonic/gin"
)

func BenchmarkTest00143(c *gin.Context) {
	forwardedIP := c.GetHeader("X-Forwarded-For")
	var result *string
	row := DB.QueryRow("SELECT name FROM users WHERE id = $1", forwardedIP)
	var name string
	if scanErr := row.Scan(&name); scanErr == nil {
		result = &name
	}
	if result == nil {
		c.String(404, "not found")
		return
	}
	c.JSON(http.StatusOK, map[string]string{"name": *result})
}
