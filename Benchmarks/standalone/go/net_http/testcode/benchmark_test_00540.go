package testcode

import (
	"net/http"
	"strconv"
	"strings"
)

func BenchmarkTest00540(w http.ResponseWriter, r *http.Request) {
	_, header, err := r.FormFile("upload")
	if err != nil {
		http.Error(w, "bad upload", http.StatusBadRequest)
		return
	}
	uploadName := header.Filename
	data := strings.Join(strings.FieldsFunc(uploadName, func(r rune) bool { return r == ' ' || r == '\t' }), " ")
	requested, _ := strconv.Atoi(data)
	wrapped := int32(requested + 1)
	w.Header().Set("X-Wrapped", strconv.Itoa(int(wrapped)))
}
