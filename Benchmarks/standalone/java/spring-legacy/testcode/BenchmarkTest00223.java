import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.multipart.MultipartFile;
import org.springframework.http.ResponseEntity;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.WebDataBinder;

@RestController
@Validated
public class BenchmarkTest00223 {
    @InitBinder
    public void restrictBinding(WebDataBinder binder) {
        binder.setDisallowedFields("id");
    }

    @ExceptionHandler(Exception.class)
    public ResponseEntity<String> handleFailure(Exception ex) {
        return ResponseEntity.status(500).body("request failed");
    }

    @PostMapping(path="/BenchmarkTest00223", consumes="multipart/form-data")
    public void BenchmarkTest00223(@RequestPart("file") MultipartFile file, HttpServletRequest request, HttpServletResponse response) throws Exception {
        String uploadName = file != null ? file.getOriginalFilename() : "";
        java.util.Map.Entry<String,String> kv = java.util.Map.entry(uploadName, "request");
        String data = kv.getKey();
        try { Double.parseDouble(data); }
        catch (NumberFormatException e) { response.sendError(400); return; }
        String boundedVal = data;
        Object codeResult = new org.springframework.expression.spel.standard.SpelExpressionParser().parseExpression(boundedVal).getValue();
        response.setHeader("X-Code-Result", String.valueOf(codeResult));
        response.setContentType("application/json");
        response.getWriter().print("{\"id\":0}");
    }
}
