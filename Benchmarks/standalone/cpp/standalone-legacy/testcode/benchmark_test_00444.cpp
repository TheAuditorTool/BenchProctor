#include <iostream>
#include <string>
#include <cstdio>
#include <cstdlib>

void benchmark_test_00444(int, char **)
{
    const char *user_input_env = std::getenv("MULTIPART_FIELD");
    std::string user_input = user_input_env ? std::string(user_input_env) : std::string();
    std::string data = user_input;
    for (char &_c : data) if (_c == '\n') _c = ' ';
    std::string _ckval = data;
    for (char &_c : _ckval) if (_c == '\r' || _c == '\n') _c = ' ';
    for (char &_c : _ckval) if (_c == '\r' || _c == '\n') _c = ' ';
    std::fputs((std::string("Set-Cookie: session=") + _ckval + "; HttpOnly; SameSite=Strict; Path=/\r\n").c_str(), stdout);
}
