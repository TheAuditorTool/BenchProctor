#include <iostream>
#include <string>
#include <cstdio>
#include <cstdlib>
#include <unistd.h>

void benchmark_test_00111(int, char **)
{
    const char *user_input_env = std::getenv("GRAPHQL_INPUT");
    std::string user_input = user_input_env ? std::string(user_input_env) : std::string();
    std::string data = user_input;
    for (char &_c : data) if (_c == '\n') _c = ' ';
    std::string arg = std::string("/var/app/data/") + data.substr(data.find_last_of('/') + 1);
    if (FILE *_f = std::fopen(arg.c_str(), "w")) std::fclose(_f);
}
