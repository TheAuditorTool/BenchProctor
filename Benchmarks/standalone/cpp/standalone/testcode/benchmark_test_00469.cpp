#include <iostream>
#include <string>
#include <cstdlib>
#include <unistd.h>

void benchmark_test_00469(int, char **)
{
    const char *user_input_env = std::getenv("HTTP_COOKIE");
    std::string user_input = user_input_env ? std::string(user_input_env) : std::string();
    const char *_argv[] = { "/bin/echo", user_input.c_str(), nullptr };
    execv("/bin/echo", const_cast<char *const *>(_argv));
}
