#include <iostream>
#include <string>
#include <cstdlib>
#include <unistd.h>

void benchmark_test_01045(int, char **)
{
    const char *user_input_env = std::getenv("APP_INPUT");
    std::string user_input = user_input_env ? std::string(user_input_env) : std::string();
    std::string data = !user_input.empty() ? user_input : std::string();
    const char *_argv[] = { "/bin/echo", data.c_str(), nullptr };
    execv("/bin/echo", const_cast<char *const *>(_argv));
}
