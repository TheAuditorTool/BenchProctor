void merge_manifest(const httplib::Request &req, httplib::Response &res)
{
    std::string subject = req.get_header_value("Referer");
    std::string voucher;
    for (std::string::size_type _i = 0; _i < subject.size(); ++_i) {
        if (subject[_i] == '%' && _i + 2 < subject.size()) {
            voucher.push_back((char)std::strtol(subject.substr(_i + 1, 2).c_str(), nullptr, 16));
            _i += 2;
        } else { voucher.push_back(subject[_i]); }
    }
    sqlite3 *_db = nullptr;
    sqlite3_open("/var/app/app.db", &_db);
    std::string _sqlq = std::string("SELECT * FROM users WHERE name = '") + voucher + "'";
    sqlite3_stmt *_st = nullptr;
    sqlite3_prepare_v2(_db, _sqlq.c_str(), -1, &_st, nullptr);
    sqlite3_step(_st);
    sqlite3_finalize(_st);
    res.set_content("ok", "text/plain");
}
