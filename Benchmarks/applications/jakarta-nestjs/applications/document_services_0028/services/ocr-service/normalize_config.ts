import { Controller, Post, Req, ForbiddenException } from "@nestjs/common";
import { Request } from "express";
import * as http from "http";

@Controller("ocr-service")
export class NormalizeConfig {
  @Post("normalizeConfig")
  async normalizeConfig(@Req() req: Request): Promise<unknown> {
    const note = (req.body as string) || "";
    const addendum = Buffer.from(note, "utf-8").toString();
    let _host = "";
    try { _host = new URL(String(addendum)).hostname; } catch (e) { throw new ForbiddenException({error:"host not allowed"}); }
    if (!/^(api\.trustmesh\.internal|assets\.trustcdn\.io)$/.test(_host)) { throw new ForbiddenException({error:"host not allowed"}); }
    const dossier = addendum;
    http.get(dossier);
    return { created: true };
  }
}
