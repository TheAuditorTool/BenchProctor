package testcode

import (
	"net/http"
	"strings"

	"github.com/gin-gonic/gin"
)

func BenchmarkTest00060(c *gin.Context) {
	refererValue := c.GetHeader("Referer")
	capture := func() string { return strings.TrimSpace(refererValue) }
	data := capture()
	http.SetCookie(c.Writer, &http.Cookie{Name: "session", Value: data, HttpOnly: true, SameSite: http.SameSiteStrictMode})
	c.JSON(200, gin.H{"code": "OK"})
}
